import type { Network } from '../domain/ast';
import type { HardwareProfile } from '../domain/hardware';
import { DEFAULT_FORMAT, formatIl, ladToIlNetworks, type FormatOptions } from './lad-to-il';
import type { SymbolMap, TranspileDiagnostic } from './types';

/**
 * STEP 7-Micro/WIN source export.
 *
 * Two shapes are produced from the same instruction list:
 *  - `wrapper: 'none'` (default) emits bare `NETWORK` blocks, which is what the STL editor accepts
 *    when you paste into it.
 *  - `wrapper: 'main'` adds the `ORGANIZATION_BLOCK MAIN` / `BEGIN` / `END_ORGANIZATION_BLOCK`
 *    scaffolding that a file-level import expects.
 *
 * Caveat, stated plainly: the exact grammar Micro/WIN's importer accepts has not been verified
 * against the real software here. Treat the output as a faithful STL rendering, and confirm one
 * import before relying on it for a batch.
 */

export interface ExportOptions extends FormatOptions {
  readonly wrapper: 'none' | 'main';
  /** Block name used with `wrapper: 'main'`. */
  readonly blockName: string;
  /** ISO timestamp for the header; injectable so exports can be reproducible in tests. */
  readonly timestamp: string;
  /** Append `// <symbol name>` to instructions whose operand has one. */
  readonly annotateSymbols: boolean;
  readonly fileName: string;
}

export interface ExportFile {
  readonly fileName: string;
  readonly content: string;
  /** Present only when a non-empty `SymbolMap` was supplied. */
  readonly symbolTable?: { readonly fileName: string; readonly content: string };
  readonly diagnostics: readonly TranspileDiagnostic[];
}

const BANNER = '//=============================================================================';

export const DEFAULT_EXPORT_OPTIONS: Omit<ExportOptions, 'timestamp'> = {
  ...DEFAULT_FORMAT,
  wrapper: 'none',
  blockName: 'MAIN',
  annotateSymbols: false,
  fileName: 'program.awl',
};

function header(profile: HardwareProfile, timestamp: string, networkCount: number): string {
  return [
    BANNER,
    '// Generated by MAE Academy PLC Simulator',
    `// Target CPU: ${profile.model}`,
    `// Date: ${timestamp}`,
    `// Networks: ${networkCount}`,
    BANNER,
  ].join('\n');
}

/** Valid Micro/WIN symbol: letters, digits, underscore; never leading with a digit. */
const SYMBOL_RE = /^[A-Za-z_][A-Za-z0-9_]*$/;

export function exportMicroWin(
  networks: readonly Network[],
  profile: HardwareProfile,
  symbols?: SymbolMap,
  options: Partial<ExportOptions> = {},
): ExportFile {
  const settings: ExportOptions = {
    ...DEFAULT_EXPORT_OPTIONS,
    timestamp: new Date().toISOString(),
    ...options,
  };

  const generated = ladToIlNetworks(networks);
  const diagnostics: TranspileDiagnostic[] = [...generated.diagnostics];
  const ilNetworks = generated.value ?? [];

  const annotated = settings.annotateSymbols && symbols ? annotate(ilNetworks, symbols) : ilNetworks;
  const body = formatIl(annotated, settings);

  const sections = [header(profile, settings.timestamp, ilNetworks.length)];
  if (settings.wrapper === 'main') {
    sections.push(`ORGANIZATION_BLOCK ${settings.blockName}`, 'TITLE=Program Comments', 'BEGIN', body, 'END_ORGANIZATION_BLOCK');
  } else {
    sections.push(body);
  }

  const file: ExportFile = {
    fileName: settings.fileName,
    content: `${sections.join('\n\n')}\n`,
    diagnostics,
  };

  const symbolTable = symbols === undefined ? undefined : buildSymbolTable(symbols, profile, settings, diagnostics);
  return symbolTable === undefined ? file : { ...file, symbolTable };
}

type IlNetworks = ReturnType<typeof ladToIlNetworks>['value'];

/** Adds the symbolic name of the first address operand as a trailing comment. */
function annotate(networks: NonNullable<IlNetworks>, symbols: SymbolMap): NonNullable<IlNetworks> {
  return networks.map((network) => ({
    ...network,
    lines: network.lines.map((line) => {
      if (line.comment !== undefined) return line;
      for (const text of line.operands) {
        const entry = symbols[text.toUpperCase()];
        if (entry) return { ...line, comment: entry.name };
      }
      return line;
    }),
  }));
}

/**
 * Micro/WIN symbol table, tab separated with a header row — the layout the Symbol Table grid
 * accepts on paste and that `.sym` export produces.
 */
function buildSymbolTable(
  symbols: SymbolMap,
  profile: HardwareProfile,
  settings: ExportOptions,
  diagnostics: TranspileDiagnostic[],
): { fileName: string; content: string } | undefined {
  const entries = Object.entries(symbols);
  if (entries.length === 0) return undefined;

  const seen = new Map<string, string>();
  const rows: string[] = [];

  for (const [rawAddress, entry] of entries) {
    const address = rawAddress.toUpperCase();
    if (!SYMBOL_RE.test(entry.name)) {
      diagnostics.push({
        code: 'INVALID_OPERAND',
        severity: 'error',
        message: `Symbol "${entry.name}" is not a valid Micro/WIN identifier`,
        address,
      });
      continue;
    }
    const duplicate = seen.get(entry.name.toUpperCase());
    if (duplicate !== undefined) {
      diagnostics.push({
        code: 'INVALID_OPERAND',
        severity: 'error',
        message: `Symbol "${entry.name}" is assigned to both ${duplicate} and ${address}`,
        address,
      });
      continue;
    }
    seen.set(entry.name.toUpperCase(), address);
    rows.push([entry.name, address, entry.comment ?? ''].join('\t'));
  }

  rows.sort((a, b) => a.localeCompare(b));
  const content = [
    BANNER,
    '// Symbol Table',
    `// Target CPU: ${profile.model}`,
    `// Date: ${settings.timestamp}`,
    BANNER,
    '// Symbol\tAddress\tComment',
    ...rows,
    '',
  ].join('\n');

  return { fileName: settings.fileName.replace(/\.[^.]+$/, '') + '.sym', content };
}
