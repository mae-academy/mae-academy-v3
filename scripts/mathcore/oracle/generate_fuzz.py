"""
Differential fuzzing oracle (STEPS.md §10): evaluates fuzz.ts expressions with mpmath at 50 digits.

    python generate_fuzz.py FUZZ_INPUTS.json > ../../../shared/mathcore/__golden__/fuzz.json

A point is kept only where a double-precision evaluator can be judged at 1e-12: the same expression evaluated by
mpmath at 53-bit precision (correctly rounded operations, i.e. an ideal float64 evaluator) must agree with the
50-digit value within STABILITY. Points that fail are numerically unstable (cancellation, overflow) and say nothing
about the engine. Domain errors (null) are kept: the engine must return a non-finite value there too.
"""
import json
import sys

from mpmath import mp, workprec

from evaluate import depends_on_signed_zero, evaluate

STABILITY = 1e-14
MAX_MAGNITUDE = 1e100


def main():
    data = json.load(open(sys.argv[1]))
    out = []
    dropped = 0
    for entry in data["entries"]:
        samples = []
        for x in entry["points"]:
            v = evaluate(entry["mathjson"], {"x": x})
            signed_zero = depends_on_signed_zero()
            with workprec(53):
                v53 = evaluate(entry["mathjson"], {"x": x})
            # Unstable: the result hinges on the sign of a zero, or an ideal float64 evaluator disagrees on whether
            # the point is even in the domain (ln(sin π) is ln of a tiny positive double but ln of 0 exactly).
            if signed_zero or (v is None) != (v53 is None):
                dropped += 1
                continue
            if v is None:
                samples.append({"x": x, "value": None})
                continue
            if v == 0 or abs(v) > MAX_MAGNITUDE or abs(v53 - v) > STABILITY * abs(v):
                dropped += 1
                continue
            samples.append({"x": x, "value": mp.nstr(v, 25, strip_zeros=False)})
        if samples:
            out.append({"id": entry["id"], "mathjson": entry["mathjson"], "samples": samples})
    json.dump(
        {
            "about": "Fixed-seed differential fuzz subset (STEPS.md §10). mpmath 50 digits; null = domain error. "
            "Generated by scripts/mathcore/oracle; do not edit by hand.",
            "seed": data["seed"],
            "expressions": len(data["entries"]),
            "unstablePointsDropped": dropped,
            "tolerance": 1e-12,
            "entries": out,
        },
        sys.stdout,
        separators=(",", ":"),
    )
    sys.stdout.write("\n")


if __name__ == "__main__":
    main()
