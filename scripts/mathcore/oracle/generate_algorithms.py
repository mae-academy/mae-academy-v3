"""
Algorithm golden values (STEPS.md §8, §10): special functions now; linear algebra, ODE, interpolation and
distributions are added by their phases.

    python generate_algorithms.py > ../../../shared/mathcore/__golden__/algorithms.json
"""
import json
import sys

from mpmath import mp, mpf

mp.dps = 50


def s(v):
    return mp.nstr(mpf(v), 25, strip_zeros=False)


def special():
    xs = [-2.5, -0.75, 0.1, 0.5, 1, 2.5, 7.3, 20.2, 100.5, 170.4]
    out = {
        "gamma": [{"args": [x], "value": s(mp.gamma(x))} for x in xs],
        "lnGamma": [{"args": [x], "value": s(mp.log(abs(mp.gamma(x))))} for x in [0.1, 0.5, 2.5, 7.3, 20.2, 100.5, 1e4, -0.75]],
        "erf": [{"args": [x], "value": s(mp.erf(x))} for x in [-4.5, -2.9, -0.7, -1e-3, 0.2, 0.49, 0.51, 1.7, 2.99, 3.01, 5.5]],
        "erfc": [{"args": [x], "value": s(mp.erfc(x))} for x in [-2, -0.3, 0.1, 0.49, 0.51, 1.2, 3.5, 6, 12, 26]],
    }
    beta = []
    for x, a, b in [(0.1, 0.5, 0.5), (0.3, 2, 3), (0.5, 10, 10), (0.9, 0.7, 4.5), (0.01, 3, 0.4), (0.75, 50, 20), (0.6, 1, 1)]:
        beta.append({"args": [x, a, b], "value": s(mp.betainc(a, b, 0, x, regularized=True))})
    out["incompleteBeta"] = beta
    gp, gq = [], []
    for a, x in [(0.5, 0.2), (1, 1), (2.5, 1.7), (3, 6), (10, 4), (10, 15), (30, 25), (0.3, 5)]:
        gp.append({"args": [a, x], "value": s(mp.gammainc(a, 0, x, regularized=True))})
        gq.append({"args": [a, x], "value": s(mp.gammainc(a, x, mp.inf, regularized=True))})
    out["incompleteGammaP"] = gp
    out["incompleteGammaQ"] = gq
    return out


def main():
    json.dump(
        {
            "about": "Algorithm golden values (STEPS.md §8). mpmath 50 digits, 25 significant digits printed. "
            "Generated by scripts/mathcore/oracle; do not edit by hand.",
            "mpmath": __import__("mpmath").__version__,
            "special": special(),
        },
        sys.stdout,
        indent=1,
    )
    sys.stdout.write("\n")


if __name__ == "__main__":
    main()
