"""
Step 2 of the golden pipeline (STEPS.md §10, ADR-5): evaluates every corpus expression with mpmath at 50 digits.

    python scripts/mathcore/oracle/generate.py INPUTS.json > shared/mathcore/__golden__/eval.json

A point is kept only where the relative-error test is meaningful:
  - the value is finite and non-zero, and
  - the condition number |x·f'(x)/f(x)| is at most MAX_CONDITION (an ill-conditioned point measures the
    function's sensitivity to the rounding of x, not the evaluator's accuracy).
Domain errors (complex, pole) are kept as null: the engine must return NaN or ±Infinity there.
"""
import json
import sys

from mpmath import mp, mpf

from evaluate import evaluate

MAX_CONDITION = 1e4
DIGITS = 25


def _value(expr, s):
    v = evaluate(expr, {"x": s})
    return mpf("nan") if v is None else v


def condition(expr, x, fx):
    try:
        d = mp.diff(lambda s: _value(expr, s), mpf(x))
    except Exception:  # noqa: BLE001 — non-differentiable point (floor, abs at 0): keep it
        return 0
    if mp.isnan(d):
        return 0
    return abs(mpf(x) * d / fx)


def main():
    data = json.load(open(sys.argv[1]))
    out = []
    for entry in data["entries"]:
        samples = []
        for x in entry["points"]:
            v = evaluate(entry["mathjson"], {"x": x})
            if v is None:
                samples.append({"x": x, "value": None})
                continue
            if v == 0 or condition(entry["mathjson"], x, v) > MAX_CONDITION:
                continue
            samples.append({"x": x, "value": mp.nstr(v, DIGITS, strip_zeros=False)})
        out.append({"id": entry["id"], "latex": entry["latex"], "mathjson": entry["mathjson"], "samples": samples})
    json.dump(
        {
            "about": "Golden corpus (STEPS.md §10). Values: mpmath at 50 digits, printed to 25 significant digits; "
            "null = domain error. Generated by scripts/mathcore/oracle; do not edit by hand.",
            "computeEngine": data["computeEngine"],
            "mpmath": __import__("mpmath").__version__,
            "precisionDigits": mp.dps,
            "tolerance": 1e-12,
            "entries": out,
        },
        sys.stdout,
        indent=1,
    )
    sys.stdout.write("\n")


if __name__ == "__main__":
    main()
